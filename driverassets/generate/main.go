package main

import (
	"crypto/sha256"
	"encoding/hex"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

type packageSpec struct {
	variableName    string
	assetDirectory  string
	versionConstant map[string]string
}

func main() {
	specs := []packageSpec{
		{
			variableName:    "VBoxUSB",
			assetDirectory:  filepath.Join("..", "internal", "vboxusb", "assets"),
			versionConstant: map[string]string{"amd64": "VBoxUSBVersion", "arm64": "VBoxUSBVersion"},
		},
		{
			variableName:    "VHCI",
			assetDirectory:  filepath.Join("..", "internal", "usbipvhci", "assets"),
			versionConstant: map[string]string{"amd64": "VHCIAMD64Version", "arm64": "VHCIARM64Version"},
		},
	}
	var builder strings.Builder
	builder.WriteString("// Code generated by driverassets/generate. DO NOT EDIT.\n\npackage driverassets\n")
	for _, spec := range specs {
		builder.WriteString("\nvar " + spec.variableName + " = map[string]Package{\n")
		architectures := slices.Sorted(maps.Keys(spec.versionConstant))
		for _, architecture := range architectures {
			builder.WriteString("\t\"" + architecture + "\": {\n")
			builder.WriteString("\t\tVersion: " + spec.versionConstant[architecture] + ",\n")
			builder.WriteString("\t\tFiles: []File{\n")
			entries, err := os.ReadDir(filepath.Join(spec.assetDirectory, architecture))
			if err != nil {
				log.Fatal(err)
			}
			for _, entry := range entries {
				if entry.IsDir() || strings.HasSuffix(entry.Name(), ".license") {
					continue
				}
				content, readErr := os.ReadFile(filepath.Join(spec.assetDirectory, architecture, entry.Name()))
				if readErr != nil {
					log.Fatal(readErr)
				}
				digest := sha256.Sum256(content)
				builder.WriteString("\t\t\t{\"" + entry.Name() + "\", \"" + hex.EncodeToString(digest[:]) + "\"},\n")
			}
			builder.WriteString("\t\t},\n\t},\n")
		}
		builder.WriteString("}\n")
	}
	err := os.WriteFile("digests.go", []byte(builder.String()), 0o644)
	if err != nil {
		log.Fatal(err)
	}
}
